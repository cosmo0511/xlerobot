# (회전 q/e, 속도 r/f)으로 돌아서 z/x, c/v 가 안 먹혔습니다.
#
# bi_so_base_leader 의 기본값:
#   회전 q/e, 속도 r/f, 종료 t
# 우리가 쓰는 것 (실제로 쓰던 배치 그대로):
#   회전 z/x, 속도 c/v, 종료 t
#
# ■ 바퀴 잠금 (여기서 못 바꿉니다 — arm_key, 기본 g)
# ---------------------------------------------------------------------------
# 바퀴는 **잠긴 상태로 시작**합니다. g 를 눌러야 움직입니다. 키보드 리스너가
# 전역이라, 다른 창에서 친 wasd 로 로봇이 움직이는 걸 막으려는 장치입니다.
# =============================================================================

